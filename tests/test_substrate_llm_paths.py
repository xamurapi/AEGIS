def test_code_self_modification_no_change_path():
    async def run():
        s = _make_substrate()
        # Stub the code modifier so nothing touches the real package source.
        s.code_modifier.list_sources = lambda: [
            {"path": "toy.py", "immutable": False, "size": 100}]
        s.code_modifier.read_source = lambda p: "x = 1\n"

        async def _propose(path, src, state):
            return {"success": True, "parsed": {
                "should_modify": False, "reason": "already optimal"}}

        s.llm.propose_code_change = _propose
        applied = {"n": 0}
        s.code_modifier.apply_modification = lambda *a, **k: applied.__setitem__("n", applied["n"] + 1) or {"status": "applied"}
        await s._code_self_modification()
        assert applied["n"] == 0  # no modification attempted
    asyncio.run(run())


def test_code_self_modification_applies_when_safe(monkeypatch):
    async def run():
        # Code self-modification is opt-in (audit C2); enable it for this path.
        import aegis.layers.substrate as substrate_mod
        monkeypatch.setattr(substrate_mod, "CODE_SELF_MOD_ENABLED", True)
        s = _make_substrate()
        s.code_modifier.list_sources = lambda: [
            {"path": "toy.py", "immutable": False, "size": 100}]
        s.code_modifier.read_source = lambda p: "x = 1\n"

        async def _propose(path, src, state):
            return {"success": True, "parsed": {
                "should_modify": True,
                "modified_code": "x = 2  # improved\n",
                "description": "bump constant"}}

        s.llm.propose_code_change = _propose
        calls = {"applied": 0}

        def _apply(path, code, desc, author="llm"):
            calls["applied"] += 1
            return {"status": "applied_pending_restart"}

        s.code_modifier.apply_modification = _apply
        await s._code_self_modification()
        # Passed ethics + self-preservation (benign change) -> apply was called.
        assert calls["applied"] == 1
        assert s._code_mod_count_session == 1
    asyncio.run(run())
